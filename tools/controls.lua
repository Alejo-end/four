-- controls.lua — write doc/controls.md, the page-by-page control map, out of
-- the script itself. It loads the real mangler.lua offscreen and asks the
-- same functions the footer asks (ctx.enc_param, ctx.key_def), page by page
-- and VOICE mode by mode, so the map cannot drift from the code the way the
-- hand-written tables did. test_control fails when doc/controls.md is stale.
--
--   lua tools/controls.lua [out]        # from the repo root; out defaults
--                                       # to doc/controls.md

local OUT = arg[1] or "doc/controls.md"

local env = dofile("tools/uisim/env.lua")
env.install{ dir = os.getenv("TMPDIR") or "/tmp" }
include = function(m) return dofile(m .. ".lua") end
local real_print = print
print = function() end
dofile("mangler.lua")
init()
print = real_print

local CTX
for i = 1, 255 do
  local n, v = debug.getupvalue(key, i)
  if n == nil then break end
  if n == "ctx" then CTX = v end
end
assert(CTX, "could not reach the script's ctx")
local T = dofile("tools/harness.lua")

local function enc_cell(n, alt)
  CTX.alt = alt
  local id = CTX.enc_param(n)
  CTX.alt = false
  return id and ("`" .. id .. "`") or "none"
end

local function key_cell(n)
  CTX.alt = false
  local def = CTX.key_def(n)
  return def and def.label or "none"
end

local out = {
  "# mangler controls",
  "",
  "GENERATED by `lua tools/controls.lua` from the script's own encoder and key",
  "tables. Do not edit by hand; regenerate after changing a page.",
  "",
  "Everywhere: E1 selects the page, K1 is shift, K1+E1 morphs toward the selected",
  "scene, K1+K2 is STOP, and K1+K3 is DRY on a tap or erases the page's",
  "material when held for about a second.",
  "",
  "Compound targets: `@win_move` slides the take window, `@lay_move` slides the",
  "selected layer's loop, `@lay_level` and `@lay_rate` set the selected layer's",
  "level and rate.",
  "",
  "| Page | E2 | E3 | K1+E2 | K1+E3 | K2 | K3 | Erase |",
  "|---|---|---|---|---|---|---|---|",
}

local MODES = { { 5, "PLAY" }, { 2, "GRAIN" }, { 3, "WARP" }, { 4, "PV" } }

for i, name in ipairs(T.pages()) do
  T.goto_page(i)
  local variants = name == "VOICE" and MODES or { { nil, nil } }
  for _, m in ipairs(variants) do
    if m[1] then params:set("mode", m[1]) end
    local label = m[2] and (name .. " (" .. m[2] .. ")") or name
    out[#out + 1] = string.format("| %s | %s | %s | %s | %s | %s | %s | %s |",
      label, enc_cell(2, false), enc_cell(3, false), enc_cell(2, true),
      enc_cell(3, true), key_cell(2), key_cell(3),
      CTX.page_erase() and "yes" or "no")
  end
  if name == "VOICE" then params:set("mode", 5) end
end

local f = assert(io.open(OUT, "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print("wrote " .. OUT)
