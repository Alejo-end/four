#!/usr/bin/env python3
"""Write a dated results page from the gate and performance records.

    python3 tools/device/report.py 2026-11-06
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def rows(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def gate_titles():
    """Check number -> its name, from doc/device-gate.md."""
    titles = {}
    with open(os.path.join(ROOT, "doc", "device-gate.md")) as f:
        for line in f:
            m = re.match(r"\|\s*(\d+\.\d+b?)\s*\|\s*([^|]+)\|", line)
            if m:
                titles[m.group(1)] = m.group(2).replace("**", "").strip()
    return titles


def cell(text, limit=260):
    text = str(text).replace("|", "/").replace("\n", " ")
    return text if len(text) <= limit else text[:limit - 3] + "..."


def main(date):
    out = os.path.join(ROOT, "doc", "measurements", date)
    results = rows(os.path.join(out, "gate.jsonl"))
    titles = gate_titles()
    seen = {r["id"] for r in results}
    missing = sorted(set(titles) - seen, key=lambda c: [int(x) for x in re.findall(r"\d+", c)])
    counts = {}
    for r in results:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    lines = [
        f"# Device results, {date}",
        "",
        "GENERATED by `tools/device/report.py`. See doc/norns-platform.md for what the numbers mean.",
        "",
        "`pass` means that the measurement decides the check. `measured` means that the numbers are",
        "right, but a person must still listen or look. `you` needs a person or hardware that was",
        "not connected. No grid, Launchpad, crow, MIDI gear or line source was connected: a private",
        "scsynth fed test signals to crone's input ports.",
        "",
        "Summary: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + f", not run {len(missing)}.",
        "",
    ]
    fails = [r for r in results if r["status"] in ("fail", "error")]
    if fails:
        lines += ["## Failures", "", "| # | Check | Result |", "|---|---|---|"]
        lines += [f"| {r['id']} | {cell(titles.get(r['id'], ''), 60)} | {cell(r['note'])} |" for r in fails]
        lines.append("")
    lines += ["## All checks", "", "| # | Check | Status | Result |", "|---|---|---|---|"]
    lines += [f"| {r['id']} | {cell(titles.get(r['id'], ''), 60)} | {r['status']} | {cell(r['note'])} |" for r in results]
    lines.append("")
    if missing:
        lines += ["Not run: " + ", ".join(missing) + ".", ""]
    perf = rows(os.path.join(out, "performance.jsonl"))
    for kind, title in (("state", "Each state"), ("page", "Each page, with the take playing"),
                        ("voices", "Pad voices, with no drone"), ("budget", "The whole instrument"),
                        ("soak", "Soak")):
        some = [p for p in perf if p["kind"] == kind and "avg" in p]
        if not some:
            continue
        lines += [f"## {title}", "", "| State | scsynth avg % | peak % | xruns | fps | system idle % | Busiest threads |",
                  "|---|---|---|---|---|---|---|"]
        for p in some:
            lines.append(f"| {cell(p['name'], 80)} | {p['avg']} | {p['peak']} | {p.get('xruns', '')} | {p.get('fps', '')} "
                         f"| {p.get('idle', '')} | {cell(', '.join(p.get('threads', [])[:3]), 70)} |")
        lines.append("")
    trials = [p for p in perf if p["kind"] == "two_server"]
    if trials:
        lines += ["## One server against two, with mangler running", "",
                  "| Trial | Thread A % | Thread B % | JACK avg % | JACK peak % | Seconds | xruns |", "|---|---|---|---|---|---|---|"]
        for p in trials:
            lines.append(f"| {p['name']} | {p['thread_a']} | {p['thread_b']} | {p['jack_avg']} | {p['jack_peak']} | {p.get('seconds', '')} | {p['xruns']} |")
        lines.append("")
    for kind, title in (("patch", "softcut into the engine"), ("error", "Errors")):
        some = [p for p in perf if p["kind"] == kind]
        if some:
            lines += [f"## {title}", ""]
            lines += ["- " + cell(json.dumps({k: v for k, v in p.items() if k != "kind"}), 500) for p in some]
            lines.append("")
    with open(os.path.join(out, "README.md"), "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.join(out, "README.md"), counts, "not run", len(missing))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "2026-11-06")
