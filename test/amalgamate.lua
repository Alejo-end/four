-- amalgamate.lua — build the single-file distribution of four.
-- reads four.lua, inlines each `local X = include "lib/name"` as an
-- immediately-invoked function wrapping that module's source (semantically
-- identical: module locals stay scoped, the return value lands in X), and
-- writes dist/four_single.lua. the dist file is GENERATED — never edit
-- it by hand; rebuild after any change:
--
--   lua test/amalgamate.lua            # from the repo root
--
-- verify like any screen change: luac -p dist/four_single.lua, then run
-- the render suite against it (the harness takes the script path as arg 1).

local SRC = arg[1] or "four.lua"
local OUT = arg[2] or "dist/four_single.lua"

local function slurp(path)
  local f = assert(io.open(path, "r"), "cannot open " .. path)
  local s = f:read("*a")
  f:close()
  return s
end

local main = slurp(SRC)
local inlined = 0

local body = main:gsub("(%s*)local%s+(%w+)%s*=%s*include%s*\"lib/([%w_]+)\"",
  function(lead, var, mod)
    inlined = inlined + 1
    local src = slurp("lib/" .. mod .. ".lua")
    return string.format(
      "%slocal %s = (function()  -- inlined lib/%s.lua\n%s\nend)()",
      lead, var, mod, src)
  end)

assert(inlined == 15, "expected 15 lib includes, matched " .. inlined ..
  " — update test/amalgamate.lua if modules changed")

local header = [[
-- four (single-file build)
-- GENERATED by test/amalgamate.lua from four.lua + lib/*.lua — do not
-- edit this file; edit the modules and rebuild.
--
-- this file replaces dust/code/four/four.lua as a drop-in. the
-- SuperCollider engine is NOT inlined: lib/Engine_Four.sc must still
-- exist next to it — and exactly ONCE on the whole device. never create a
-- second folder with another copy of the .sc: a duplicate Engine_Four
-- class hangs EVERY norns script on "LOADING".

]]

local out_dir = OUT:match("^(.*)/")
if out_dir then os.execute(("mkdir -p %q"):format(out_dir)) end
local f = assert(io.open(OUT, "w"))
f:write(header, body)
f:close()
print("wrote " .. OUT .. " (" .. inlined .. " modules inlined)")
