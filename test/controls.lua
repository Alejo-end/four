-- controls.lua: write doc/controls.md, the page-by-page control map, out of
-- the script itself. It loads the real four.lua offscreen and asks the
-- same functions the footer asks (ctx.enc_param, ctx.key_def, and the
-- footer's own word for each knob), page by page, VOICE mode by mode and
-- MOTION row by row, so the map cannot drift from the code the way the
-- hand-written tables did. test_control fails when doc/controls.md is stale.
--
--   lua test/controls.lua [out]        # from the repo root; out defaults
--                                       # to doc/controls.md

local OUT = arg[1] or "doc/controls.md"

local env = dofile("test/uisim/env.lua")
env.install{ dir = os.getenv("TMPDIR") or "/tmp" }
include = function(m) return dofile(m .. ".lua") end
local real_print = print
print = function() end
dofile("four.lua")
init()
print = real_print

local function upvalue(fn, name)
  for i = 1, 255 do
    local n, v = debug.getupvalue(fn, i)
    if n == nil then break end
    if n == name then return v end
  end
end
local CTX, Mp = upvalue(key, "ctx"), upvalue(redraw, "Mpages")
assert(CTX and Mp, "could not reach the script's ctx and the pages module")
local T = dofile("test/harness.lua")

-- a knob: the word the footer shows at rest, then the param id
local function enc_cell(n, alt)
  CTX.alt = alt
  local id = CTX.enc_param(n)
  CTX.alt = false
  if not id then return "none" end
  return Mp.footer_word(id) .. " `" .. id .. "`"
end

-- a key: its word, what a hold does, and * for the punch law
local function key_cell(n)
  CTX.alt = false
  local def = CTX.key_def(n)
  if not def then return "none" end
  local s = def.label
  if def.hold_label then
    s = s .. ", hold " .. def.hold_label
  elseif def.gate then
    s = s .. ", sounds while held"
  elseif def.pon then
    s = s .. "*"
  end
  return s
end

-- a row's cells, after its label
local function cells()
  return string.format(" %s | %s | %s | %s | %s | %s | %s |",
    enc_cell(2, false), enc_cell(3, false), enc_cell(2, true),
    enc_cell(3, true), key_cell(2), key_cell(3),
    CTX.page_erase() and "yes" or "no")
end

