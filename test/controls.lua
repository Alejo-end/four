-- the VOICE rail's order, then OFF (TRACKS K2 turns a track off)
local MODES = { { 5, "PLAY" }, { 2, "GRAIN" }, { 3, "WARP" }, { 4, "PV" },
  { 6, "CLOUD" }, { 1, "OFF" } }
local FOCUS = { { 1, "lanes" } }
for i = 1, CTX.lfo.N do FOCUS[#FOCUS + 1] = { i + 1, "LFO " .. i } end

for i, name in ipairs(T.pages()) do
  T.goto_page(i)
  params:set("track_sel", 1)
  local variants = name == "VOICE" and MODES
    or (name == "MOTION" and FOCUS or { { nil, nil } })
  for _, m in ipairs(variants) do
    if m[1] then params:set(name == "VOICE" and "mode" or "mod_focus", m[1]) end
    out[#out + 1] = "| " .. (m[2] and (name .. " (" .. m[2] .. ")") or name) .. " |" .. cells()
  end
  if name == "VOICE" then params:set("mode", 5) end
  if name == "MOTION" then params:set("mod_focus", 1) end
end

-- tracks 2 to 4: every row of a track page that is not track 1's row with
-- `t2_` ids (the hold's track number aside)
local function same(a, b)
  a = a:gsub("`t2_", "`"):gsub("TRK %d", "TRK n")
  b = b:gsub("TRK %d", "TRK n")
  return a == b
end
local extra = {}
for i, name in ipairs(T.pages()) do
  if name == "TAKE" or name == "VOICE" or name == "FILTER" or name == "EFFECT" then
    T.goto_page(i)
    local variants = name == "VOICE" and MODES or { { nil, nil } }
    for _, m in ipairs(variants) do
      params:set("track_sel", 1)
      if m[1] then params:set("mode", m[1]) end
      local one = cells()
      params:set("track_sel", 2)
      if m[1] then params:set("t2_mode", m[1]) end
      local two = cells()
      if not same(two, one) then
        extra[#extra + 1] = "| " .. name .. " 2" .. (m[2] and (" (" .. m[2] .. ")") or "")
          .. " |" .. two
      end
    end
    params:set("track_sel", 1)
    params:set("mode", 5); params:set("t2_mode", 1)
  end
end
if #extra > 0 then
  out[#out + 1] = ""
  out[#out + 1] = "On tracks 2 to 4 (shown for track 2) these rows differ from track 1's."
  out[#out + 1] = "Track 1 alone has the erosion, so VOICE in PLAY keeps SPEED and PITCH"
  out[#out + 1] = "on K1 and FRZ on K2."
  out[#out + 1] = ""
  out[#out + 1] = "| Page | E2 | E3 | K1+E2 | K1+E3 | K2 | K3 | Erase |"
  out[#out + 1] = "|---|---|---|---|---|---|---|---|"
  for _, r in ipairs(extra) do out[#out + 1] = r end
end

local f = assert(io.open(OUT, "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print("wrote " .. OUT)
